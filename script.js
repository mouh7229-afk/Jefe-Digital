if (!prefersReducedMotion) {
  document.querySelectorAll(".magnetic").forEach(btn => {
    btn.addEventListener("pointermove", e => {
      if (!hasFinePointer) return;
      const r = btn.getBoundingClientRect();
      const x = (e.clientX - r.left - r.width / 2) * .08;
      const y = (e.clientY - r.top - r.height / 2) * .08;
      btn.style.transform = `translate3d(${x}px, ${y}px, 0)`;
    });
    btn.addEventListener("pointerleave", () => { btn.style.transform = ""; });
  });

  // Small pointer parallax on the 3D hero scene. CSS animation remains in control of rotation.
  const scene = document.querySelector(".scene");
  if (scene && hasFinePointer) {
    scene.addEventListener("pointermove", e => {
      const rect = scene.getBoundingClientRect();
      const x = ((e.clientX - rect.left) / rect.width - .5) * 10;
      const y = ((e.clientY - rect.top) / rect.height - .5) * -10;
      scene.style.setProperty("--scene-tilt-x", `${x}deg`);
      scene.style.setProperty("--scene-tilt-y", `${y}deg`);
    });
    scene.addEventListener("pointerleave", () => {
      scene.style.setProperty("--scene-tilt-x", "0deg");
      scene.style.setProperty("--scene-tilt-y", "0deg");
    });
  }
}

