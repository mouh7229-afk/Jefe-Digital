// Mobile navigation: supports click, Escape, and closes after choosing a section.
const nav = document.querySelector(".nav");
const menuToggle = document.querySelector(".menu-toggle");
const closeMenu = () => {
  if (!nav || !menuToggle) return;
  nav.classList.remove("menu-open");
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", translations[document.documentElement.lang]?.["nav.open"] || "Open navigation");
};
if (menuToggle && nav) {
  menuToggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("menu-open");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
    menuToggle.setAttribute("aria-label", translations[document.documentElement.lang]?.[isOpen ? "nav.close" : "nav.open"] || (isOpen ? "Close navigation" : "Open navigation"));
  });
  nav.querySelectorAll(".nav-links a").forEach(link => link.addEventListener("click", closeMenu));
  document.addEventListener("keydown", e => { if (e.key === "Escape") closeMenu(); });
  window.addEventListener("resize", () => { if (window.innerWidth > 900) closeMenu(); }, { passive: true });
}
