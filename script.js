// Accessible mobile navigation
const nav = document.querySelector(".nav");
const menuToggle = document.querySelector(".menu-toggle");
if (menuToggle && nav) {
  menuToggle.addEventListener("click", () => {
    const isOpen = nav.classList.toggle("menu-open");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
    menuToggle.setAttribute("aria-label", isOpen ? "Close navigation" : "Open navigation");
  });
  nav.querySelectorAll(".nav-links a").forEach(link => link.addEventListener("click", () => {
    nav.classList.remove("menu-open"); menuToggle.setAttribute("aria-expanded", "false");
    menuToggle.setAttribute("aria-label", "Open navigation");
  }));
  document.addEventListener("keydown", e => { if (e.key === "Escape") { nav.classList.remove("menu-open"); menuToggle.setAttribute("aria-expanded", "false"); } });
}
